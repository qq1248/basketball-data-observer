// --- Utility Functions ---

/**
 * Map an ESPN basketball team display name to its Chinese name.
 * Returns the original English name if no mapping is found.
 */
export function mapBasketballTeam(espnName: string): string {
  const trimmed: string = espnName.trim();
  return BASKETBALL_MAPPINGS[trimmed] ?? espnName;
}

/**
 * 将任意来源的篮球队名归一化到标准中文名。
 * 1. 先用 BASKETBALL_MAPPINGS 精确匹配
 * 2. 去前后空白、统一常见变体（FC/BC/女篮/男篮等后缀）
 * 3. 返回标准中文名（无映射时返回原名 trim 后结果）
 */
export function normalizeBasketballTeamName(name: string): string {
  if (!name) return '';
  const trimmed: string = name.trim();
  if (BASKETBALL_MAPPINGS[trimmed]) return BASKETBALL_MAPPINGS[trimmed];
  const lower: string = trimmed.toLowerCase();
  for (const [alias, canonical] of Object.entries(BASKETBALL_MAPPINGS)) {
    if (alias.toLowerCase() === lower) return canonical;
  }
  return trimmed;
}

